import type { CanvasPresetId } from "@/editor/canvas";

export type ShadowPreset = "none" | "soft" | "medium" | "strong";
export type BackgroundKind = "solid" | "gradient" | "image" | "none";

export interface GradientBlob {
  /** Centre as a fraction of the canvas. */
  x: number;
  y: number;
  /** Radius as a fraction of the canvas's longer side. */
  r: number;
  color: string;
}

export interface GradientDef {
  id: string;
  name: string;
  base: string;
  blobs: GradientBlob[];
}

export interface BackgroundState {
  kind: BackgroundKind;
  /** Each kind's choice is kept while another is active, so switching back restores it. */
  color: string;
  gradientId: string;
  /** Gradient generated by "Match colors"; used when gradientId is "matched". */
  matched: GradientDef | null;
  imageId: string | null;
}

/**
 * How the screenshot sits inside the screen. zoom ≥ 1 enlarges past "cover";
 * pan runs from -1 (left/top edge) to 1 (right/bottom edge) across any overflow.
 */
export interface Crop {
  zoom: number;
  panX: number;
  panY: number;
}

export interface DeviceInstance {
  /** Stable id for this device in the scene. */
  key: string;
  deviceId: string;
  colorId: string;
  /** Centre of the device as a fraction of the canvas, so it survives canvas changes. */
  x: number;
  y: number;
  /** Multiplier on the automatic fit. 1 = device fills 80% of the canvas. */
  scale: number;
  /** Degrees, clockwise. */
  rotation: number;
  glare: boolean;
  screenshotId: string | null;
  crop: Crop;
}

export type LayoutId =
  "solo" | "duo" | "stack" | "fan" | "laptop-phone" | "phone-tablet";

export interface Scene {
  version: 2;
  canvas: {
    preset: CanvasPresetId;
    custom: { width: number; height: number; label?: string };
  };
  background: BackgroundState;
  layout: LayoutId;
  /** Drawn in order: later devices sit on top. */
  devices: DeviceInstance[];
  shadow: ShadowPreset;
}

export interface Size {
  width: number;
  height: number;
}

export interface Rect extends Size {
  x: number;
  y: number;
}
